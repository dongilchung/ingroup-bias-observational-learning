clear; clc;

jobs = local_cpm_permutation_jobs();
job_idx = 5;
jobs_to_run = job_idx; % Use 1:numel(jobs) to run every CPM permutation job.

for idx = jobs_to_run
    run_cpm_job(jobs(idx));
end

function result = run_cpm_job(job)
result = CPM_permutation( ...
    job.condition_name, ...
    job.edge_sign, ...
    job.behavior_name, ...
    job.output_file);
end

function jobs = local_cpm_permutation_jobs()
jobs = struct( ...
    'condition_name', {'Doc', 'Doc', 'Soc', 'Soc', 'Pol', 'Pol', 'Doc', 'Doc', 'Soc', 'Soc', 'Pol', 'Pol'}, ...
    'edge_sign', {'pos', 'neg', 'pos', 'neg', 'pos', 'neg', 'pos', 'neg', 'pos', 'neg', 'pos', 'neg'}, ...
    'behavior_name', {'LoseBias', 'LoseBias', 'LoseBias', 'LoseBias', 'LoseBias', 'LoseBias', ...
                      'WinBias', 'WinBias', 'WinBias', 'WinBias', 'WinBias', 'WinBias'}, ...
    'output_file', {'rho_pos_doc_losebias.mat', 'rho_neg_doc_losebias.mat', ...
                    'rho_pos_soc_losebias.mat', 'rho_neg_soc_losebias.mat', ...
                    'rho_pos_pol_losebias.mat', 'rho_neg_pol_losebias.mat', ...
                    'rho_pos_doc_winbias.mat', ...
                    'rho_neg_doc_winbias.mat', 'rho_pos_soc_winbias.mat', 'rho_neg_soc_winbias.mat', ...
                    'rho_pos_pol_winbias.mat', 'rho_neg_pol_winbias.mat'});
end
