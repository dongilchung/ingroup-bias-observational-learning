        8});

n_models = numel(model_specs);
model_name = strings(n_models, 1);
description = strings(n_models, 1);
chain_file = strings(n_models, 1);
n_parameters = nan(n_models, 1);
n_subjects = nan(n_models, 1);
n_datapoints = nan(n_models, 1);
integrated_log_likelihood = nan(n_models, 1);
BIC = nan(n_models, 1);

for model_idx = 1:n_models
    model_name(model_idx) = string(model_specs(model_idx).model_name);
    description(model_idx) = string(model_specs(model_idx).description);
    n_parameters(model_idx) = model_specs(model_idx).n_parameters;
    chain_file(model_idx) = fullfile('OL', model_specs(model_idx).model_name, 'OL_chain.mat');

    model_chain_file = fullfile(model_root, model_specs(model_idx).model_name, 'OL_chain.mat');
    [BIC(model_idx), integrated_log_likelihood(model_idx), ...
        n_subjects(model_idx), n_datapoints(model_idx)] = calculate_iBIC( ...
        model_chain_file, n_parameters(model_idx), trials_per_subject);
end

iBIC_table = table(model_name, description, chain_file, n_parameters, ...
    n_subjects, n_datapoints, integrated_log_likelihood, BIC);
iBIC_table.delta_BIC = iBIC_table.BIC - min(iBIC_table.BIC);
iBIC_table = sortrows(iBIC_table, 'BIC');

display_iBIC = table(iBIC_table.model_name, iBIC_table.BIC, ...
    'VariableNames', {'model_name', 'iBIC_score'});
disp(display_iBIC);

function [bic, integrated_log_likelihood, n_subjects, n_datapoints] = calculate_iBIC( ...
    model_chain_file, n_parameters, trials_per_subject)

if ~isfile(model_chain_file)
    error('model_iBIC:MissingChainFile', 'Cannot find %s.', model_chain_file);
end

chain = load(model_chain_file, 'log_lik');
if ~isfield(chain, 'log_lik')
    error('model_iBIC:MissingLogLik', 'log_lik is missing from %s.', model_chain_file);
end

log_lik = chain.log_lik;
n_subjects = size(log_lik, 2);
n_datapoints = trials_per_subject * n_subjects;

likelihood_by_subject = mean(exp(log_lik), 1);
integrated_log_likelihood = sum(log(likelihood_by_subject));
bic = -2 * integrated_log_likelihood + n_parameters * log(n_datapoints);
end
