        'Prediction-dependent learning: lr, k, lrPredWin_In/Out, lrNopredLose_In/Out, invTemp', ...
        'Previous choice bias: lr, k, g1, g2, invTemp', ...
        'Previous choice bias: lr_In, lr_Out, k, g1, g2, invTemp', ...
        'Previous choice bias: lr, k_In, k_Out, g1, g2, invTemp', ...
        'Previous choice bias: lr, k, g1_In, g2_In, g1_Out, g2_Out, invTemp', ...
        'Previous-choice-dependent learning: lr, k, lrPrevWin_In/Out, lrNoprevLose_In/Out, invTemp'}, ...
    'n_parameters', { ...
        3, ...
        4, ...
