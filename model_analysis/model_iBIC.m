        'Model_RCImC1', ...
        'Model_RCImC2', ...
        'Model_RCImC3', ...
        'Model_RCImC4', ...
        'Model_RCImC5'}, ...
    'description', { ...
        'RL: lr, invTemp', ...
        'RL: lr_In, lr_Out, invTemp', ...
        'Choice imitation: k, invTemp', ...
        'Choice imitation: k_In, k_Out, invTemp', ...
        'RL + choice imitation: lr, k, invTemp', ...
        'RL + choice imitation: lr_In, lr_Out, k, invTemp', ...
        'RL + choice imitation: lr, k_In, k_Out, invTemp', ...
        'Prediction bias: lr, k, w1, w2, invTemp', ...
        'Prediction bias: lr_In, lr_Out, k, w1, w2, invTemp', ...
        'Prediction bias: lr, k_In, k_Out, w1, w2, invTemp', ...
